-- Paginated search over ZoneMTA's `mail_messagestore` joined with `mail_senderdelivered` and `mail_queuerelease`. Supports envelope, header, and metadata filters; sortable; choose recipient-level or message-level grouping. Use to investigate delivery issues, find specific messages by Message-ID, audit bounce rates, or feed an analytics dashboard. Sibling ops: `getStats`, `getMailDeliverability`, `delistBlock` (clear a block surfaced by a bounce).  **Path param:** - `id` (integer, required) — `mail_id` from `getMailList` (omit to span all owned mail users — admin-only).  **Query params:** - `from`, `to` (string) — envelope address, exact match. - `headerfrom`, `replyto` (string) — header address, exact match; validated as email. - `subject` (string) — LIKE match on subject. - `mailid` (string, 18–19 chars) — relay id, exact. - `messageId` (string) — Message-ID header, substring match. - `origin` (string) — submitter IP, exact. - `mx` (string) — destination MX hostname, LIKE. - `delivered` (integer 0/1). - `startDate`, `endDate` (Unix timestamp or `strtotime`-parseable string). - `skip` (integer, default 0), `limit` (integer 1–10000, default 100). - `sort` (`time`), `dir` (`asc`/`desc`, default `desc`). - `groupby` (`recipient` default — one row per delivery attempt; `message` — one row per `_id`).  **Returns** (schema `MailLog`): `{total, skip, limit, emails: [{id, _id, from, to, subject, messageId, time, mxHostname, delivered, code, response, recipient, ...}]}`.  **Auth:** Session/API key. Ownership enforced.  **Errors:** `400` bad input, `401`. 
-- 
-- AuthMethod: 'AuthApiKeySessionIdCookieAuth', 'AuthApiKeyApiKeyAuth', 'AuthApiKeySessionIdHeaderAuth'
-- 
viewMailLog
  :: Id -- ^ "id" -  The mail service ID. Use `mail_id` from `GET /mail`.
  -> ApiRequest ViewMailLog MimeNoContent MailLog MimeJSON
viewMailLog (Id id) =
  _mkRequest "GET" ["/mail/",toPath id,"/log"]
    `_hasAuthType` (P.Proxy :: P.Proxy AuthApiKeySessionIdCookieAuth)
    `_hasAuthType` (P.Proxy :: P.Proxy AuthApiKeyApiKeyAuth)
    `_hasAuthType` (P.Proxy :: P.Proxy AuthApiKeySessionIdHeaderAuth)

data ViewMailLog  

-- | /Optional Param/ "id" - The numeric ID of the mail order to filter by.  When omitted, logs from the first active mail order are returned.  Obtain valid IDs from `GET /mail` or `GET /mail/{id}`.
instance HasOptionalParam ViewMailLog Id2 where
  applyOptionalParam req (Id2 xs) =
    req `addQuery` toQuery ("id", Just xs)

-- | /Optional Param/ "origin" - Filter by the originating IP address from which the message was submitted to the relay.  Must be a valid IPv4 or IPv6 address.
instance HasOptionalParam ViewMailLog Origin where
  applyOptionalParam req (Origin xs) =
    req `addQuery` toQuery ("origin", Just xs)

-- | /Optional Param/ "mx" - Filter by the MX hostname the relay attempted delivery to.  For example `mx.google.com` would return messages destined for Gmail recipients. Maps to `mxHostname` in the `MailLogEntry` response.
instance HasOptionalParam ViewMailLog Mx where
  applyOptionalParam req (Mx xs) =
    req `addQuery` toQuery ("mx", Just xs)

-- | /Optional Param/ "from" - Filter by SMTP envelope `MAIL FROM` address (exact match).  This is the address the relay used for bounce handling and may differ from the `From:` message header.  For header-level filtering use `headerfrom`.
instance HasOptionalParam ViewMailLog From where
  applyOptionalParam req (From xs) =
    req `addQuery` toQuery ("from", Just xs)

-- | /Optional Param/ "to" - Filter by SMTP envelope `RCPT TO` address (exact match).  This is the delivery address used by the relay and may differ from the `To:` header when BCC recipients are involved.
instance HasOptionalParam ViewMailLog To where
  applyOptionalParam req (To xs) =
    req `addQuery` toQuery ("to", Just xs)

-- | /Optional Param/ "subject" - Filter by email `Subject` header (exact match).  MIME-encoded subjects are decoded automatically in the response.
instance HasOptionalParam ViewMailLog Subject where
  applyOptionalParam req (Subject xs) =
    req `addQuery` toQuery ("subject", Just xs)

-- | /Optional Param/ "mailid" - Filter by the relay-assigned mail ID string (exact match).  This corresponds to the `id` field in `MailLogEntry` and to the `text` value returned by the sending endpoints on success.  Format is an 18-19 character hexadecimal string such as `185997065c60008840`.
instance HasOptionalParam ViewMailLog Mailid where
  applyOptionalParam req (Mailid xs) =
    req `addQuery` toQuery ("mailid", Just xs)

-- | /Optional Param/ "messageId" - Filter by the `Message-ID` email header using a substring (case-insensitive) match. The `Message-ID` is assigned by the sending mail client and is visible in the `messageId` field of `MailLogEntry`.
instance HasOptionalParam ViewMailLog MessageId where
  applyOptionalParam req (MessageId xs) =
    req `addQuery` toQuery ("messageId", Just xs)

-- | /Optional Param/ "replyto" - Filter by the `Reply-To` message header address (exact match).  Only returns messages where this header was explicitly set.
instance HasOptionalParam ViewMailLog Replyto where
  applyOptionalParam req (Replyto xs) =
    req `addQuery` toQuery ("replyto", Just xs)

-- | /Optional Param/ "headerfrom" - Filter by the `From` message header address (exact match).  This is the human-visible sender address and may differ from the SMTP envelope `from` parameter when sending on behalf of another address.
instance HasOptionalParam ViewMailLog Headerfrom where
  applyOptionalParam req (Headerfrom xs) =
    req `addQuery` toQuery ("headerfrom", Just xs)

-- | /Optional Param/ "delivered" - Filter by delivery status.  `1` returns only messages that were successfully delivered to the destination MX.  `0` returns messages that are still queued, deferred, or failed.  Omit to return all messages regardless of delivery status.
instance HasOptionalParam ViewMailLog Delivered where
  applyOptionalParam req (Delivered xs) =
    req `addQuery` toQuery ("delivered", Just xs)

-- | /Optional Param/ "skip" - Number of records to skip for pagination.  Use in combination with `limit` to page through large result sets.  Defaults to `0` (no skip).
instance HasOptionalParam ViewMailLog Skip where
  applyOptionalParam req (Skip xs) =
    req `addQuery` toQuery ("skip", Just xs)

-- | /Optional Param/ "limit" - Maximum number of records to return per page.  Defaults to `100`. Maximum allowed value is `10000`.  The response also includes a `total` field with the full matched count so you can calculate the number of pages.
instance HasOptionalParam ViewMailLog Limit where
  applyOptionalParam req (Limit xs) =
    req `addQuery` toQuery ("limit", Just xs)

-- | /Optional Param/ "startDate" - Earliest date to include.  Accepts either a Unix timestamp (integer seconds since epoch) or a date string parseable by `strtotime()` such as `2024-01-15` or `last monday`.  Messages with a `time` value **greater than or equal to** this value will be included.
instance HasOptionalParam ViewMailLog StartDate where
  applyOptionalParam req (StartDate xs) =
    req `addQuery` toQuery ("startDate", Just xs)

-- | /Optional Param/ "endDate" - Latest date to include.  Accepts either a Unix timestamp (integer seconds since epoch) or a date string parseable by `strtotime()` such as `2024-01-31` or `yesterday`. Messages with a `time` value **less than or equal to** this value will be included.
instance HasOptionalParam ViewMailLog EndDate where
  applyOptionalParam req (EndDate xs) =
    req `addQuery` toQuery ("endDate", Just xs)

-- | /Optional Param/ "sort" - Field to sort results by.  Currently only `time` is supported (sorts by internal row ID which corresponds to chronological order).
instance HasOptionalParam ViewMailLog Sort where
  applyOptionalParam req (Sort xs) =
    req `addQuery` toQuery ("sort", Just xs)

-- | /Optional Param/ "dir" - Sort direction.  `desc` returns newest first (default), `asc` returns oldest first.
instance HasOptionalParam ViewMailLog Dir where
  applyOptionalParam req (Dir xs) =
    req `addQuery` toQuery ("dir", Just xs)

-- | /Optional Param/ "groupby" - Controls how results are grouped.  `recipient` (default) returns one row per delivery attempt — a message sent to 4 recipients produces 4 rows, each with its own `recipient`, `delivered`, `response`, and delivery metadata.  `message` collapses to one row per unique message ID; delivery-level fields will reflect one arbitrary recipient per message.  The `total` count in the response matches the grouping mode.
instance HasOptionalParam ViewMailLog Groupby where
  applyOptionalParam req (Groupby xs) =
    req `addQuery` toQuery ("groupby", Just xs)
-- | @application/json@
instance Produces ViewMailLog MimeJSON

